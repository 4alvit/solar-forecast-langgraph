"""Deterministic synthetic input generator for the offline evaluation example."""

from __future__ import annotations

import json
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

from .evaluation import ForecastLedger, digest, evaluate, iso


def create_demo(directory: str | Path, *, now: datetime | None = None) -> dict:
    """Write a fresh demonstration, refusing to replace any existing directory.

    The numbers are constructed to exercise metrics, not generated by the
    operational model or measured from a solar installation.
    """
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=False)
    now = now or datetime.now(UTC)
    start = datetime(2026, 9, 29, tzinfo=UTC)
    actuals = []
    forecasts = []
    for day in range(5):
        daily: list[dict[str, Any]] = []
        for hour in range(24):
            target = start + timedelta(days=day, hours=hour)
            daylight = 7 <= hour < 18
            energy = float((hour - 6) * (18 - hour) * 10 * (1 + day / 20)) if daylight else 0.0
            actuals.append(
                {
                    "schema_version": 1,
                    "site_id": "synthetic-demo",
                    "panel_id": "all",
                    "unit": "Wh",
                    "interval_seconds": 3600,
                    "target_start": iso(target),
                    "available_at": iso(target + timedelta(hours=1)),
                    "energy_wh": energy,
                    "quality": "valid",
                    "daylight": "day" if daylight else "night",
                    "source": "deterministic synthetic fixture; not measured generation",
                }
            )
            daily.append({"target_start": iso(target), "energy_wh": energy})
        if day < 2:
            continue
        issue = start + timedelta(days=day, minutes=-30)
        for variant, factor in (("baseline", 1.10), ("candidate", 1.05)):
            forecasts.append(
                {
                    "schema_version": 1,
                    "site_id": "synthetic-demo",
                    "panel_id": "all",
                    "unit": "Wh",
                    "interval_seconds": 3600,
                    "variant": variant,
                    "issued_at": iso(issue),
                    "inputs_available_at": iso(issue),
                    "training_end": "2026-10-01T00:00:00+00:00" if day > 2 else iso(issue),
                    "source_sha256": digest("evaluation-demo-v1"),
                    "config_sha256": digest({"factor": factor}),
                    "input_sha256": digest(daily),
                    "provenance": "synthetic",
                    "source": "constructed errors; not model predictions",
                    "points": [
                        {**point, "energy_wh": point["energy_wh"] * factor} for point in daily
                    ],
                }
            )
    plan = {
        "schema_version": 1,
        "site_id": "synthetic-demo",
        "panel_id": "all",
        "timezone": "UTC",
        "train_end": "2026-10-01T00:00:00Z",
        "validation_end": "2026-10-02T00:00:00Z",
        "test_end": "2026-10-04T00:00:00Z",
        "min_lead_hours": 0.5,
        "max_lead_hours": 24,
        "variants": ["baseline", "candidate", "persistence"],
        "training_policy": "frozen",
    }
    for name, records in (("forecasts", forecasts), ("actuals", actuals)):
        with (directory / f"{name}.jsonl").open("x", encoding="utf-8") as output:
            for record in records:
                output.write(json.dumps(record, sort_keys=True, allow_nan=False) + "\n")
    (directory / "plan.json").write_text(json.dumps(plan, indent=2) + "\n")
    with ForecastLedger(directory / "ledger.sqlite") as ledger:
        ledger.append("forecasts", forecasts, now=now)
        ledger.append("actuals", actuals, now=now)
        report = evaluate(ledger, plan, as_of=now, allow_retrospective=True)
    report["demonstration"] = "Synthetic arithmetic example; not a forecast-quality claim"
    (directory / "report.json").write_text(json.dumps(report, indent=2, allow_nan=False) + "\n")
    return report
